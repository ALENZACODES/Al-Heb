for (const [sit, list] of Object.entries(SIT)) {
  list.forEach((t, i) => {
    const [he, translit, en, register, notes, forms] = t;
    const id = `${sit}-${String(i + 1).padStart(2, '0')}`;
    const rec = {
      id, he: he.normalize('NFC'), translit, en, register, situation: sit,
      notes: notes || '',
      pointed: true,
      review: register === 'slang' ? 'native-speaker-needed: slang/register and spelling' : 'native-speaker-needed: pointing and register',
      source: 'original (written for this project from general knowledge; no phrasebook copied)',
      license: 'original (project-owned)',
    };
    if (forms) {
      rec.gendered = true;
      rec.forms = { m: { he: forms.m[0].normalize('NFC'), translit: forms.m[1] }, f: { he: forms.f[0].normalize('NFC'), translit: forms.f[1] } };
    }
    phrases.push(rec);
  });
}
