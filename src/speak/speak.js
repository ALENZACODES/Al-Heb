/** Which tab to open: ctx.query.tab, else location.hash (#/speak/read or #/speak?tab=read), else the first. */
export function tabFromLocation(query, hash) {
  const norm = (t) => { t = String(t || '').toLowerCase(); t = TAB_ALIAS[t] || t; return TAB_IDS.includes(t) ? t : null; };
  const q = norm(query?.tab); if (q) return q;
  const m = String(hash || '').match(/^#?\/speak(?:\/([A-Za-z-]+))?(?:\?(.*))?$/);
  if (m) return norm(m[1]) || norm(new URLSearchParams(m[2] || '').get('tab')) || 'say';
  return 'say';
}
