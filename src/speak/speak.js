/**
 * Say it (#/speak): spoken practice. DRAFT, unreviewed. Three screens in one module (query `tab`):
 *   say     - show a word or phrase from the vocabulary list, play the model (clip if one exists, else the browser voice),
 *             then capture the learner's attempt: browser SpeechRecognition (he-IL) where it exists, else record-and-listen-back
 *             (MediaRecorder), else a plain "I said it / Not yet".
 *   drills  - minimal-pair listening (bet/vet, het/khaf, kamatz a/o, shin/sin) built from existing words.
 *   sounds  - "Sounds that differ by tradition": which look-alike pairs sound different in the learner's tradition (settings
 *             `congregation`), from data/speak/minimal-pairs.json (rule-generated by the pronunciation lane, unreviewed), plus a quiz.
 *   read    - read a short prayer aloud line by line; the recognizer's text is compared word by word with the verbatim line
 *             (letters only) and missed words are marked.
 *   shadow  - listen to a line, say it right after, rate yourself 1-3.
 *   history - scoring history and a weakest-sounds report.
 * Tabs are links like #/speak?tab=read and also work from #/speak/read (read from ctx.query or location.hash), so no router
 * entry is needed for them.
 * Hebrew comes only from data/speak/ (built from data/vocab/words.json); nothing here invents Hebrew.
 * The browser recognizer is UNVERIFIED for Hebrew: Aleph has not measured it; its verdicts are hints. Nothing is uploaded by
 * Aleph; the browser's own recognizer may send audio to its vendor, and the screen says so before the first use.
 * Module pattern: mount(root, ctx) -> unmount. Store key speak.v1. ctx extras for tests: ctx.clock {now}, ctx.rng,
 * ctx.speak {data:{sets, setItems, pairs}, RecognitionCtor, MediaRecorderCtor, getUserMedia, synth, UtteranceCtor, caps}.
 */
