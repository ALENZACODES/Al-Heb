// The pinned alef-tools build (assets/vendor/_alef-tools/offline-llm@<version>/) and the two places the app reads it:
// Ask the Torah's "closest checked questions" and a unit page's checked extra practice. Unit tier: no browser, no network.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { check, vendorDir, pin } from '../tools/alef-tools/sync-offline-llm.mjs';
import { isOnDemand } from '../tools/build-precache.mjs';
import { VERSION, FOLDER } from '../src/alef-tools/offline-llm.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const DIR = vendorDir;
const listing = JSON.parse(readFileSync(join(DIR, 'dist.json'), 'utf8'));
const units = (kind) => listing.files.filter((f) => f.path.startsWith(kind + '/')).map((f) => f.path.slice(kind.length + 1, -5));
const man = { files: listing.files, examples: units('examples'), quiz: units('quiz') };
const MiB = 1024 * 1024;
// The four-letter Name with any points between the letters (written with escapes on purpose).
const NAME = /י[֑-ׇ]*ה[֑-ׇ]*ו[֑-ׇ]*ה/;
// "AI" is matched in capitals only (CAPS): Ai is a city in the Torah and belongs in the answers.
const BANNED = /chatgpt|claude|gemini|openai|anthropic|\bllm\b|language model|machine[- ](generated|written|translated)|dictalm|generated by/i;
const CAPS = /\bAI\b|\bA\.I\./;
/** fetch stand-in that serves the vendored files from disk */
const fetchTools = async (url) => {
  const p = fileURLToPath(url);
  if (!existsSync(p)) return { ok: false, status: 404 };
  const buf = readFileSync(p);
  return { ok: true, status: 200, json: async () => JSON.parse(buf.toString('utf8')), arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) };
};

test('the vendored build is exactly the pinned alef-tools commit, file for file', () => {
  assert.match(pin.commit, /^[0-9a-f]{40}$/, 'the pin names a full commit');
  assert.deepEqual(check(), []);
  assert.equal(listing.version, VERSION, 'the reader and the pin agree on the version');
  assert.equal(pathToFileURL(DIR + '/').href, FOLDER.href);
});

test('none of it is in the first install: the vendored files are not listed at all, and the reader is on demand', () => {
  const pre = read('precache-manifest.js');
  const first = pre.slice(pre.indexOf('self.ALEF_PRECACHE'), pre.indexOf('self.ALEF_ON_DEMAND'));
  // Integration (lanes together): the shared rule lists vendored alef-tools CODE as on demand, so a screen that imports it still
  // opens offline. Nothing of it is installed up front, and this lane's data files (the index and its numbers) are not listed at all.
  assert.doesNotMatch(first, /_alef-tools/, 'assets/vendor is never installed up front');
  assert.doesNotMatch(pre, /_alef-tools\/offline-llm@[^"]*\.(json|vec)/, 'the search index is never listed');
  assert.doesNotMatch(first, /src\/alef-tools\//);
  assert.ok(isOnDemand('src/alef-tools/offline-llm.js'));
  for (const f of ['src/ask/ask.view.js', 'src/curriculum/practical.view.js']) assert.doesNotMatch(first, new RegExp(f.replace(/[/.]/g, '\\$&')), f + ' stays out of the first install');
});

test('size budget: search index at most 1.5 MiB in all, each unit file at most 300 KiB', () => {
  const size = (p) => statSync(join(DIR, p)).size;
  const index = size('search/index.v1.json') + (existsSync(join(DIR, 'search/index.v1.vec')) ? size('search/index.v1.vec') : 0);
  assert.ok(index <= 1.5 * MiB, `search index is ${index} bytes`);
  for (const f of man.files) if (/^(examples|quiz)\//.test(f.path)) assert.ok(f.bytes <= 300 * 1024, `${f.path} is ${f.bytes} bytes`);
  assert.ok(gzipSync(readFileSync(join(DIR, 'search.js'))).length < 6 * 1024, 'search.js stays small');
});

test('everything a learner could be shown is marked checked, never spells the Name, and has no wording about machines', () => {
  for (const kind of ['examples', 'quiz']) {
    for (const unit of man[kind]) {
      const data = JSON.parse(readFileSync(join(DIR, kind, unit + '.json'), 'utf8'));
      assert.ok(data.items.length > 0, `${kind}/${unit} is not empty`);
      for (const it of data.items) assert.equal(it.checked, true, `${kind}/${unit} ${it.id}`);
    }
  }
  const ask = JSON.parse(readFileSync(join(DIR, 'ask/answers.v1.json'), 'utf8'));
  for (const a of Object.values(ask.answers)) {
    assert.equal(a.checked, true);
    assert.ok(a.passages.length >= 1, 'an answer always cites');
    for (const p of a.passages) assert.ok(p.quote && p.he.includes(p.quote), 'the quoted words are an exact part of the cited passage');
  }
  for (const f of man.files) {
    if (!f.path.endsWith('.json') || f.path === 'report.json' || f.path === 'dist.json') continue;
    const text = readFileSync(join(DIR, f.path), 'utf8');
    assert.doesNotMatch(text, NAME, f.path + ' spells the Name');
    const data = JSON.parse(text);
    // what a learner can be shown (not the file's own schema tag, which carries the package name)
    if (!f.path.startsWith('search/')) assert.doesNotMatch(JSON.stringify([data.answers, data.questions, data.wordings, data.items]), BANNED, f.path);
  }
  const titles = JSON.parse(readFileSync(join(DIR, 'search/index.v1.json'), 'utf8')).docs.map((d) => d[2]).join('\n');
  assert.doesNotMatch(titles, BANNED);
  assert.doesNotMatch(titles, CAPS);
});

test('every quoted span in a vendored answer matches the app\'s own Torah text exactly', () => {
  const ask = JSON.parse(readFileSync(join(DIR, 'ask/answers.v1.json'), 'utf8'));
  for (const a of Object.values(ask.answers)) for (const p of a.passages) {
    const [book, ch, v] = p.id.split('.');
    const verse = JSON.parse(read(`data/corpus/torah/${book}/${String(ch).padStart(2, '0')}.json`)).verses.find((x) => Number(x.n) === Number(v));
    assert.ok(verse, p.id + ' is a verse in the app');
    const shown = verse.he.normalize('NFD').replace(new RegExp(NAME.source + '[\\u0591-\\u05C7]*', 'g'), 'ה׳').normalize('NFC');
    assert.equal(p.he, shown, p.ref);
    assert.ok(shown.includes(p.quote), p.ref);
  }
});

test('search: an English and a Hebrew question both reach the checked Shabbat answer', async () => {
  const tools = await import('../src/alef-tools/offline-llm.js');
  const bank = JSON.parse(read('data/ask/bank.json'));
  const ids = new Set(bank.questions.map(([, a]) => a));
  for (const q of ['what does the torah say about shabbat', 'מה התורה אומרת על שבת?']) {
    const res = await tools.closest(q, { types: ['ask'], fetchImpl: fetchTools });
    assert.ok(res.length >= 1 && res.length <= 3, q);
    assert.ok(res.some((r) => /shabbat|sabbath/i.test(r.title)), q + ' -> ' + res.map((r) => r.title).join(' | '));
    for (const r of res) assert.ok(ids.has(r.id) || r.id.startsWith('an-'), 'every result is a checked answer');
  }
});

test('Ask the Torah: a question the bank cannot match shows the closest checked questions, and tapping one answers it', async () => {
  const { N } = await import('./torahread.fakedom.js');
  const { mount, CLOSEST, NO_ANSWER } = await import('../src/ask/ask.view.js');
  const root = new N('div');
  const fetchJson = async (p) => JSON.parse(read(p));
  await mount(root, { fetchJson, fetchTools, query: { q: 'מי הייתה מרים הנביאה?' } }); // Hebrew the bank has no wording for
  await new Promise((r) => setTimeout(r, 300));
  assert.ok(root.textContent.includes(CLOSEST), root.textContent.slice(-300));
  const picks = root.queryAll('.ask-log .ask-starter');
  assert.ok(picks.length >= 1 && picks.length <= 3);
  await picks[0].click();
  await new Promise((r) => setTimeout(r, 100));
  assert.match(picks[0].textContent, /Miriam/);
  assert.match(root.querySelector('.ask-log').textContent, /Exodus|Genesis|Leviticus|Numbers|Deuteronomy/, 'the tapped question is answered from the bank with its verse');
  // nonsense still gets the plain "no checked answer" line, never a guess
  const root2 = new N('div');
  await mount(root2, { fetchJson, fetchTools, query: { q: 'zzqx blorp' } });
  await new Promise((r) => setTimeout(r, 300));
  assert.ok(root2.textContent.includes(NO_ANSWER));
});

test('unit page: checked extras are drawn when the build has some for the unit, and nothing is drawn when it has none', async () => {
  await import('./torahread.fakedom.js');
  const tools = await import('../src/alef-tools/offline-llm.js');
  await tools.tools(fetchTools);
  const none = await tools.unitExtras('pu-no-such-unit', fetchTools);
  assert.deepEqual(none, { examples: [], quiz: [] });
  for (const unit of new Set([...man.examples, ...man.quiz])) {
    const x = await tools.unitExtras(unit, fetchTools);
    assert.ok(x.examples.length + x.quiz.length > 0, unit);
  }
  const { extrasBlock } = await import('../src/curriculum/practical.view.js');
  const block = extrasBlock({ examples: [{ id: 'e1', he: 'אני רוצה קפה', en: 'I want coffee' }], quiz: [{ id: 'q1', stem: 'אני רוצה ___', choices: ['קפה', 'שלום', 'תודה'], answer: 0, en: 'I want coffee' }] });
  assert.match(block.textContent, /More Example Sentences/);
  assert.match(block.textContent, /Fill in the Word/);
  const buttons = block.queryAll('button');
  assert.equal(buttons.length, 3);
  await buttons[1].click();
  assert.match(block.textContent, /Not this one/);
  await buttons[0].click();
  assert.match(block.textContent, /Yes, that is the word/);
  assert.equal(extrasBlock({ examples: [], quiz: [] }).queryAll('h2').length, 0);
});

test('the reader makes no request outside the site and the sync tool is never loaded by the app', () => {
  const src = read('src/alef-tools/offline-llm.js');
  assert.doesNotMatch(src, /https?:\/\//, 'no absolute URL: everything is read from the site itself');
  assert.doesNotMatch(read('src/ask/ask.view.js') + read('src/curriculum/practical.view.js'), /tools\/alef-tools/);
  for (const f of readdirSync(join(ROOT, 'src/alef-tools'))) assert.match(f, /\.js$/);
});
