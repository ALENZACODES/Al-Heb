#!/usr/bin/env node
// Pulls a pinned version of ALENZACODES/alef-tools into the app. No server, no npm: plain files, checked by SHA-256.
//
//   node tools/alef-tools/sync.mjs --check                 verify the vendored files against data/alef-tools.lock.json (no network; CI runs this)
//   node tools/alef-tools/sync.mjs                         fetch the commit the lock pins again and rewrite everything
//   node tools/alef-tools/sync.mjs --ref <commit or tag>   move the pin (a tag is resolved to its commit when --from is used; over the network give the commit)
//   node tools/alef-tools/sync.mjs --add words             also vendor another package of the pinned commit
//   node tools/alef-tools/sync.mjs --from ../alef-tools    read from a local checkout instead of the network (its HEAD must be the pinned commit, with a clean tree)
//
// What it writes (all committed, because the host publishes the repo as it is):
//   assets/vendor/_alef-tools/<pkg>@<version>/   each package's dist/ (code and small JSON only; never model weights)
//   src/settings/alef-tools.generated.js         package id -> folder, so no screen hard-codes a version
//   data/packs/catalog.json                      the language packs the Language packs page can list (from models.manifest.json)
//   data/alef-tools.lock.json                    the pinned commit and every vendored file with its size and SHA-256
// Nothing under assets/vendor/ is in the first install (tools/build-precache.mjs); the code is fetched the first time a screen needs it.
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const LOCK = 'data/alef-tools.lock.json';
export const VENDOR = 'assets/vendor/_alef-tools';
export const SHIM = 'src/settings/alef-tools.generated.js';
export const CATALOG = 'data/packs/catalog.json';
export const REPO = 'ALENZACODES/alef-tools';
/** The site's own folder for packs a deploy chooses to carry; tried before the pack host. */
export const SITE_PACKS = 'assets/vendor/_packs/';
const SAFE_PATH = /^(?!\/)(?!.*\.\.)[A-Za-z0-9._/-]+$/;
const ALLOWED = /\.(js|mjs|json|txt)$/; // code, small data and licence texts; anything else (weights above all) is refused
const MAX_FILE = 512 * 1024, MAX_VENDORED = 4 * 1024 * 1024;
const sha = (buf) => createHash('sha256').update(buf).digest('hex');
const json = (text) => JSON.parse(text);
const pretty = (o) => JSON.stringify(o, null, 1) + '\n';

function walk(dir, root = dir, out = []) {
  for (const n of readdirSync(dir).sort()) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p, root, out); else out.push(relative(root, p).split(sep).join('/')); }
  return out;
}

/** A reader for one commit of alef-tools: from a local checkout, or from GitHub's raw file host. */
export function sourceFor({ from, ref, fetchImpl = globalThis.fetch }) {
  if (from) {
    const git = (...a) => execFileSync('git', ['-C', from, ...a], { encoding: 'utf8' }).trim();
    const commit = git('rev-parse', `${ref || 'HEAD'}^{commit}`);
    if (git('rev-parse', 'HEAD') !== commit) throw new Error(`the checkout at ${from} is not at ${ref}`);
    if (git('status', '--porcelain')) throw new Error(`the checkout at ${from} has uncommitted changes; commit them first so the pin names real bytes`);
    return { commit, read: async (path) => readFileSync(join(from, path)) };
  }
  if (!/^[0-9a-f]{40}$/.test(ref || '')) throw new Error('over the network the pin must be a full 40-character commit (use --from for a tag or branch)');
  return { commit: ref, read: async (path) => {
    const res = await fetchImpl(`https://raw.githubusercontent.com/${REPO}/${ref}/${path}`);
    if (!res.ok) throw new Error(`${path}: ${res.status} from raw.githubusercontent.com`);
    return Buffer.from(await res.arrayBuffer());
  } };
}

/** The language packs page's list, from the tools manifest: plain-words name, what it does, budget, device needs, where to fetch. */
export function catalogFrom(manifest, commit) {
  const packs = Object.entries(manifest.packs).map(([name, p]) => {
    const models = manifest.models.filter((m) => m.pack === name);
    return { name, title: p.title, what: p.what, budgetBytes: p.budgetBytes, device: p.device, published: !!p.published, cache: p.cache, format: p.format,
      ...(p.legacy ? { legacy: p.legacy } : {}), licences: [...new Set(models.map((m) => m.licence))], credits: models.map((m) => m.attribution).filter(Boolean) };
  });
  return { schema: 'alef.packs.catalog.v1', note: 'GENERATED by tools/alef-tools/sync.mjs from alef-tools models.manifest.json. Do not edit.', tools: commit, sitePacks: SITE_PACKS, packHost: manifest.packHost, packs };
}

export function shimText(lock) {
  const pk = Object.fromEntries(Object.entries(lock.packages).map(([id, p]) => [id, { version: p.version, base: `../../${p.path}/` }]));
  const loader = lock.packages.loader;
  return `// GENERATED by tools/alef-tools/sync.mjs - do not edit. The pinned alef-tools packages (data/alef-tools.lock.json).\n`
    + `export const ALEF_TOOLS = ${JSON.stringify({ commit: lock.ref, contract: lock.contract, packages: pk })};\n`
    + `/** Address of a vendored package's entry module, for a dynamic import(). @param {string} id */\n`
    + `export const toolUrl = (id) => new URL(ALEF_TOOLS.packages[id].base + 'index.js', import.meta.url).href;\n`
    + (loader ? `export * as loader from '../../${loader.path}/index.js';\n` : '');
}

/** Fetches, checks and writes. Returns the new lock. */
export async function sync({ root = ROOT, ref, add = [], from, fetchImpl } = {}) {
  const lockFile = join(root, LOCK);
  const old = existsSync(lockFile) ? json(readFileSync(lockFile, 'utf8')) : { packages: { loader: {} } };
  const src = sourceFor({ from, ref: ref || old.ref, fetchImpl });
  const ids = [...new Set([...Object.keys(old.packages), ...add])].sort();
  const packages = {};
  for (const id of ids) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id)) throw new Error(`bad package name ${id}`);
    const listing = json((await src.read(`packages/${id}/dist/dist.json`)).toString('utf8'));
    if (listing.schema !== 'alef.dist.v1' || listing.name !== id || !/^\d+\.\d+\.\d+$/.test(listing.version)) throw new Error(`${id}: dist.json is not an alef.dist.v1 listing for this package`);
    const path = `${VENDOR}/${id}@${listing.version}`;
    const got = [];
    for (const f of listing.files) {
      if (!SAFE_PATH.test(f.path) || !ALLOWED.test(f.path)) throw new Error(`${id}: refusing ${f.path} (only code, JSON and licence texts are vendored; never weights)`);
      const buf = await src.read(`packages/${id}/dist/${f.path}`);
      if (buf.length !== f.bytes || sha(buf) !== f.sha256) throw new Error(`${id}: ${f.path} does not match dist.json (size or SHA-256)`);
      if (buf.length > (f.path.startsWith('vendor/') ? MAX_VENDORED : MAX_FILE)) throw new Error(`${id}: ${f.path} is too large to vendor (${buf.length} bytes); large data belongs in a language pack`);
      got.push({ ...f, buf });
    }
    // out with every older version of this package, in with the new one
    const vendorRoot = join(root, VENDOR);
    if (existsSync(vendorRoot)) for (const n of readdirSync(vendorRoot)) if (n.startsWith(`${id}@`)) rmSync(join(vendorRoot, n), { recursive: true, force: true });
    for (const f of got) { mkdirSync(dirname(join(root, path, f.path)), { recursive: true }); writeFileSync(join(root, path, f.path), f.buf); }
    packages[id] = { version: listing.version, path, files: got.map(({ path: p, bytes, sha256 }) => ({ path: p, bytes, sha256 })) };
  }
  const manifestBuf = await src.read('models.manifest.json');
  const manifest = json(manifestBuf.toString('utf8'));
  const catalog = pretty(catalogFrom(manifest, src.commit));
  const lock = { schema: 'alef.tools.lock.v1', note: 'The alef-tools version this app is built with. Written by tools/alef-tools/sync.mjs; do not edit by hand.',
    repo: REPO, ref: src.commit, contract: manifest.contract, packages, manifest: { sha256: sha(manifestBuf), checked: manifest.checked }, generated: {} };
  const shim = shimText(lock);
  lock.generated = { [SHIM]: sha(shim), [CATALOG]: sha(catalog) };
  for (const [rel, text] of [[SHIM, shim], [CATALOG, catalog], [LOCK, pretty(lock)]]) { mkdirSync(dirname(join(root, rel)), { recursive: true }); writeFileSync(join(root, rel), text); }
  return lock;
}

/** Verifies what is in the repo against the lock, without any network. @returns {string[]} problems */
export function check({ root = ROOT } = {}) {
  const out = [];
  const lockFile = join(root, LOCK);
  if (!existsSync(lockFile)) return [`${LOCK} is missing`];
  const lock = json(readFileSync(lockFile, 'utf8'));
  if (lock.schema !== 'alef.tools.lock.v1') out.push('the lock has an unknown schema');
  if (!/^[0-9a-f]{40}$/.test(lock.ref || '')) out.push('the lock must pin a full commit');
  if (lock.repo !== REPO) out.push(`the lock must name ${REPO}`);
  const wantDirs = new Set();
  for (const [id, p] of Object.entries(lock.packages || {})) {
    if (p.path !== `${VENDOR}/${id}@${p.version}`) { out.push(`${id}: path must be ${VENDOR}/${id}@${p.version}`); continue; }
    wantDirs.add(`${id}@${p.version}`);
    const dir = join(root, p.path);
    if (!existsSync(dir)) { out.push(`${p.path} is missing; run node tools/alef-tools/sync.mjs`); continue; }
    const have = new Set(walk(dir));
    for (const f of p.files) {
      if (!SAFE_PATH.test(f.path) || !ALLOWED.test(f.path)) { out.push(`${id}: ${f.path} is not a kind of file that may be vendored`); continue; }
      if (!have.delete(f.path)) { out.push(`${p.path}/${f.path} is missing`); continue; }
      const buf = readFileSync(join(dir, f.path));
      // git may hand text files back with CRLF on Windows; the lock names the LF bytes
      const norm = buf.includes(13) ? Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n')) : buf;
      if (norm.length !== f.bytes || sha(norm) !== f.sha256) out.push(`${p.path}/${f.path} does not match the lock (size or SHA-256)`);
    }
    for (const extra of have) out.push(`${p.path}/${extra} is not in the lock`);
  }
  const vendorRoot = join(root, VENDOR);
  if (existsSync(vendorRoot)) for (const n of readdirSync(vendorRoot)) if (!wantDirs.has(n)) out.push(`${VENDOR}/${n} is not in the lock`);
  for (const [rel, want] of Object.entries(lock.generated || {})) {
    if (!existsSync(join(root, rel))) { out.push(`${rel} is missing`); continue; }
    if (sha(readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n')) !== want) out.push(`${rel} was edited by hand or is stale; run node tools/alef-tools/sync.mjs`);
  }
  if (lock.packages?.loader && existsSync(join(root, SHIM)) && readFileSync(join(root, SHIM), 'utf8').replace(/\r\n/g, '\n') !== shimText(lock)) out.push(`${SHIM} does not match the lock`);
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
  const all = (n) => args.flatMap((a, i) => (a === n ? [args[i + 1]] : []));
  if (args.includes('--check')) {
    const problems = check();
    if (problems.length) { for (const p of problems) console.error('alef-tools: ' + p); process.exit(1); }
    const lock = json(readFileSync(join(ROOT, LOCK), 'utf8'));
    console.log(`alef-tools@${lock.ref.slice(0, 12)}: ${Object.entries(lock.packages).map(([id, p]) => `${id}@${p.version} (${p.files.length} files)`).join(', ')} match the lock`);
  } else {
    try {
      const lock = await sync({ ref: opt('--ref'), add: all('--add'), from: opt('--from') });
      console.log(`alef-tools@${lock.ref.slice(0, 12)} vendored: ${Object.entries(lock.packages).map(([id, p]) => `${id}@${p.version}`).join(', ')}`);
      console.log('Next: node tools/build-precache.mjs, then commit the vendored files with the lock.');
    } catch (e) { console.error('alef-tools: ' + String(/** @type {any} */ (e).message || e)); process.exit(1); }
  }
}
