// M-08 (12 Nov audit, lane 1): the learner-facing list of held recordings, built from the files that decide them:
//   data/lab/clip-holds.json                       recordings no screen plays until a person has listened (the player withholds them)
//   data/audio/manifest*.json rows with chirpHeld   prayer lines whose newer take failed its checks; the current recording keeps playing
//   data/books/<id>.json pages with audioHeld        book pages whose voice is held; the page shows the reason instead of Listen
// Text comes from the app's own data only (manifest rows, data/vocab/words.json, data/corpus/registry.json, data/books/index.json).
// Prayer lines are named by their registry title, never by Hebrew text, so no line can show the divine name.
//   node tools/audio/build-held-list.mjs           write data/audio/held-recordings.json
//   node tools/audio/build-held-list.mjs --check   exit 1 when the file is not what the sources build today
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUT = 'data/audio/held-recordings.json';
const J = (root, rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));
const VOICE = { f: 'Noa', m: 'Ari' };
const KIND = { syllable: 'syllable', word: 'word', line: 'phrase' };

export function buildHeldList(root = ROOT) {
  const rows = ['data/audio/manifest.json', 'data/audio/manifest-kind-word.json'].flatMap((f) => (existsSync(join(root, f)) ? J(root, f) : []));
  const byPath = new Map(rows.filter((r) => r && r.path).map((r) => [r.path, r]));
  const words = new Map(J(root, 'data/vocab/words.json').words.map((w) => [w.id, w]));
  const registry = new Map(J(root, 'data/corpus/registry.json').entries.map((e) => [e.id, e]));
  const holds = J(root, 'data/lab/clip-holds.json').paths;

  const held = holds.map((path) => {
    const [, voice, tradition, kind, file] = path.split('/');
    const id = file.replace(/\.mp3$/, '');
    const r = byPath.get(path);
    const w = words.get(id);
    const he = r?.text || w?.he || '';
    const en = (r?.english || w?.en || '').replace(/^Reading practice: /, '');
    return { path, voice, voiceName: VOICE[voice] || voice, tradition, kind: KIND[kind] || kind, he, en };
  }).sort((a, b) => a.kind.localeCompare(b.kind) || a.path.localeCompare(b.path));

  const newer = new Map();
  for (const r of rows.filter((x) => x && x.chirpHeld)) {
    const m = /^(.*)-l(\d+)$/.exec(r.id);
    const base = registry.has(r.id) ? r.id : m && registry.has(m[1]) ? m[1] : r.id;
    const part = r.kind === 'prayer' ? 'whole prayer' : m && base !== r.id ? `line ${Number(m[2])}` : 'one line';
    const key = `${base}|${part}`;
    const e = newer.get(key) || { id: r.id, title: registry.get(base)?.title || r.english || r.id, part, voices: [] };
    if (!e.voices.includes(VOICE[r.voice])) e.voices.push(VOICE[r.voice]);
    e.voices.sort();
    newer.set(key, e);
  }
  const newerHeld = [...newer.values()].sort((a, b) => a.title.localeCompare(b.title) || a.part.localeCompare(b.part, 'en', { numeric: true }));

  const index = J(root, 'data/books/index.json').books || [];
  const bookPages = [];
  for (const b of index) {
    if (!b.audioHeldPages) continue;
    const book = J(root, `data/books/${b.id}.json`);
    const pages = book.pages.map((p, i) => (p.audioHeld ? i + 1 : 0)).filter(Boolean);
    bookPages.push({ id: b.id, title: b.titleEn, pages });
  }
  return {
    schema: 'alef-held-recordings/1',
    note: `GENERATED by tools/audio/build-held-list.mjs from data/lab/clip-holds.json, the chirpHeld rows of data/audio/manifest*.json and the audioHeld pages of data/books. Do not edit by hand.`,
    counts: { held: held.length, newerHeld: rows.filter((x) => x && x.chirpHeld).length, newerHeldItems: newerHeld.length, bookPages: bookPages.reduce((n, b) => n + b.pages.length, 0) },
    held, newerHeld, bookPages,
  };
}
export const heldListText = (list) => JSON.stringify(list, null, 1) + '\n';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = heldListText(buildHeldList());
  if (process.argv.includes('--check')) {
    const now = existsSync(join(ROOT, OUT)) ? readFileSync(join(ROOT, OUT), 'utf8') : '';
    if (now !== text) { console.error(`${OUT} is stale: run node tools/audio/build-held-list.mjs`); process.exit(1); }
    console.log(`${OUT} is current`);
  } else { writeFileSync(join(ROOT, OUT), text); console.log(`wrote ${OUT}`); }
}
