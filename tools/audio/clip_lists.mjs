#!/usr/bin/env node
// Per-slot recording priority lists: for each of the 6 slots (voice x tradition) an ordered list of about 700 missing clips.
//   node tools/audio/clip_lists.mjs            print the reconciliation table
//   node tools/audio/clip_lists.mjs --write    write docs/audio/recording-kits/clip-lists/*.csv and README.md
//   node tools/audio/clip_lists.mjs --check    exit 1 if those files are stale
// Everything comes from the manifests (loadManifestFull); ids and pointed Hebrew are copied, never typed. Counts come from computeCoverage.
// Order: (1) words of core prayers, (2) lines of core prayers (core = CORE_PRAYER_RE, a draft choice in recording_needs.mjs),
// (3) lesson and vocabulary words, in the order of tools/audio/priority.mjs (ranked for the Israeli man voice; ids are shared by all slots).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadManifestFull } from './manifest_io.mjs';
import { computeCoverage, buildIndex, entryState, VOICES, TRADS } from './coverage.mjs';
import { CORE_PRAYER_RE } from './recording_needs.mjs';
import { loadData, compute } from './priority.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DIR = 'docs/audio/recording-kits/clip-lists';
export const TARGET = 700;
export const COLS = ['id', 'kind', 'pointed_hebrew', 'take_ok'];
export const SLOTS = VOICES.flatMap((v) => TRADS.map((t) => `${v}-${t}`));
export const STAGES = [
  { id: 'prayer-words', group: 'prayer-word', core: true },
  { id: 'prayer-lines', group: 'prayer-line', core: true },
  { id: 'lesson-vocab-words', groups: ['lesson-word', 'vocab-word'] },
];
const q = (s) => `"${String(s ?? '').replace(/"/g, '""')}"`;
const lineOf = (id) => id.replace(/-w\d+$/, '');

/** Required entries of one slot that the coverage tool counts as missing, per group. */
export function missingEntries(manifest, voice, tradition) {
  const index = buildIndex(manifest);
  return manifest.filter((e) => e.voice === voice && e.tradition === tradition && !e.optional && !e.aliasOf && entryState(e, index) === 'missing');
}

export function buildSlot(manifest, voice, tradition, rankById, target = TARGET) {
  const miss = missingEntries(manifest, voice, tradition);
  const stages = [];
  const pos = (e) => manifest.indexOf(e);
  for (const s of STAGES) {
    let list;
    if (s.core) list = miss.filter((e) => e.group === s.group && CORE_PRAYER_RE.test(s.group === 'prayer-word' ? lineOf(e.id) : e.id));
    else list = miss.filter((e) => s.groups.includes(e.group)).sort((a, b) => (rankById.get(a.id) ?? 1e9) - (rankById.get(b.id) ?? 1e9) || pos(a) - pos(b));
    stages.push({ stage: s, list });
  }
  const picked = []; let room = target;
  for (const { stage, list } of stages) { const take = list.slice(0, room); room -= take.length; picked.push({ stage, take, available: list.length }); }
  return { miss, picked };
}

export function build(root = ROOT) {
  const manifest = loadManifestFull(root);
  const rankById = new Map();
  for (const r of compute(loadData(root), { kinds: ['word'] }).rows) if (!rankById.has(r.id)) rankById.set(r.id, r.rank);
  const cov = computeCoverage(manifest);
  const files = {}; const summary = [];
  for (const slot of SLOTS) {
    const [voice, tradition] = slot.split('-');
    const { miss, picked } = buildSlot(manifest, voice, tradition, rankById);
    const rows = picked.flatMap((p) => p.take);
    files[`${DIR}/recording-kit-${slot}-clip-list.csv`] = [COLS.join(','), ...rows.map((e) => [q(e.id), q(e.kind), q(e.text), q('')].join(','))].join('\n') + '\n';
    const produced = rows.filter((e) => fs.existsSync(path.join(root, e.path))).length;
    const g = (name) => cov.find((c) => c.voice === voice && c.tradition === tradition && c.group === name);
    summary.push({ slot, listed: rows.length, produced, miss: miss.length, covMissing: cov.filter((c) => c.voice === voice && c.tradition === tradition).reduce((n, c) => n + c.missing, 0),
      byStage: picked.map((p) => ({ id: p.stage.id, listed: p.take.length, available: p.available })),
      groupMissing: Object.fromEntries(['prayer-word', 'prayer-line', 'lesson-word', 'vocab-word'].map((n) => [n, g(n) ? g(n).missing : 0])) });
  }
  const L = ['# Recording kit clip lists', '',
    'One ordered CSV per slot (voice x tradition): `id,kind,pointed_hebrew,take_ok`. `take_ok` is empty on purpose: the reader or reviewer fills it after listening to a take. Generated by `node tools/audio/clip_lists.mjs --write`; do not edit by hand.', '',
    'Order: words of core prayers, then lines of core prayers (core = `CORE_PRAYER_RE` in `tools/audio/recording_needs.mjs`, a draft choice), then lesson and vocabulary words in the order of `tools/audio/priority.mjs` (ranked for the Israeli man voice; the same ids are used for every slot). Each list stops at ' + TARGET + ' clips. Ids and pointed Hebrew are copied from `data/audio/manifest.json`.', '',
    `produced=${summary.reduce((n, s) => n + s.produced, 0)} (produced counts listed clips whose audio file exists on disk; it is 0 unless files exist. Nothing here is a recording.)`, '',
    'Reconciliation with `node tools/audio/coverage.mjs` (required clips, state missing). Listed + not listed = missing in the coverage tool, per group:', '',
    '| slot | listed | prayer words listed / missing | prayer lines listed / missing | lesson+vocab words listed / missing | coverage missing (all groups) |', '|---|---|---|---|---|---|'];
  for (const s of summary) {
    const [pw, pl, lv] = s.byStage;
    L.push(`| ${s.slot} | ${s.listed} | ${pw.listed} / ${s.groupMissing['prayer-word']} | ${pl.listed} / ${s.groupMissing['prayer-line']} | ${lv.listed} / ${s.groupMissing['lesson-word'] + s.groupMissing['vocab-word']} | ${s.covMissing} |`);
  }
  L.push('', 'Clips not listed (non-core prayer words and lines, lesson and vocabulary words beyond the cap, phrasebook, anchor and extra words, letters, vowel signs, syllables) are still missing and stay in the coverage report.', '');
  files[`${DIR}/README.md`] = L.join('\n');
  return { files, summary };
}

export function main(argv = process.argv.slice(2)) {
  const b = build();
  if (argv.includes('--write')) {
    fs.mkdirSync(path.join(ROOT, DIR), { recursive: true });
    for (const [rel, body] of Object.entries(b.files)) fs.writeFileSync(path.join(ROOT, rel), body);
    console.log(`wrote ${Object.keys(b.files).length} files in ${DIR}`);
  } else if (argv.includes('--check')) {
    const stale = Object.entries(b.files).filter(([rel, body]) => !fs.existsSync(path.join(ROOT, rel)) || fs.readFileSync(path.join(ROOT, rel), 'utf8') !== body).map(([r]) => r);
    if (stale.length) { console.error(`stale: ${stale.join(', ')} (run node tools/audio/clip_lists.mjs --write)`); process.exit(1); }
    console.log('clip lists are current');
  } else for (const s of b.summary) console.log(s.slot, s.listed, JSON.stringify(s.byStage), 'coverage missing', s.covMissing);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
