#!/usr/bin/env node
// Audio coverage report + "who is missing what".
//   node tools/audio/coverage.mjs                      summary table (stdout)
//   node tools/audio/coverage.mjs --write              also (re)write docs/voices/coverage.md
//   node tools/audio/coverage.mjs --check              exit 1 if docs/voices/coverage.md is stale
//   node tools/audio/coverage.mjs --who [--voice m|f] [--tradition israeli|sephardi|ashkenazi] [--group g] [--list] [--limit N]
//        who: per talent (voice x tradition) and content group, what is still missing and who can supply it (human vs TTS-possible)
// Reads data/audio/manifest.json only (run build_manifest.mjs first so it reflects files on disk). Makes no network calls.
import { loadManifestFull } from './manifest_io.mjs';
import { STATUS_LABELS, isSyntheticStatus } from '../../src/shell/audio-labels.js';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const TALENT = {
  'm|israeli': 'Ari (man), Israeli', 'f|israeli': 'Noa (woman), Israeli',
  'm|ashkenazi': 'Ashkenazi reader (man)', 'f|ashkenazi': 'Ashkenazi reader (woman)',
  'm|sephardi': 'Sephardi-values reader (man), pending decision', 'f|sephardi': 'Sephardi-values reader (woman), pending decision',
};
/** Groups where TTS is not an acceptable source (isolated sounds, names, marks): human recording only. */
export const HUMAN_ONLY_GROUPS = new Set(['letter', 'letter-final', 'letter-variant', 'letter-sound', 'letter-variant-sound', 'niqqud', 'syllable']);
export const GROUP_ORDER = ['letter', 'letter-final', 'letter-variant', 'letter-sound', 'letter-variant-sound', 'niqqud', 'syllable',
  'anchor-word', 'lesson-word', 'phrasebook', 'prayer-line', 'prayer-word', 'prayer-whole', 'corpus-other', 'other'];
export const VOICES = ['m', 'f'];
export const TRADS = ['israeli', 'sephardi', 'ashkenazi'];

export function loadManifest(root = ROOT) { return loadManifestFull(root); }

/** Who could supply this entry: 'human' always allowed; 'tts-possible' only Israeli, non-isolated content (still needs a listening test). */
export function suppliers(e) {
  if (e.tradition !== 'israeli' || HUMAN_ONLY_GROUPS.has(e.group)) return 'human only';
  return 'human or TTS (TTS unvetted)';
}

/** state of one entry: recorded | tts | via-equivalent | via-alias | missing */
export function entryState(e, index) {
  if (e.status === 'recorded') return 'recorded';
  if (isSyntheticStatus(e.status)) return 'tts'; // any synthetic status counts in the tts column
  if (e.status === 'plays-israeli') return 'via-equivalent'; // plays the Israeli clip of the same voice by the owner's rule
  if (e.aliasOf) {
    const [k, ...r] = e.aliasOf.split('/');
    const t = index.get(`${e.voice}|${e.tradition}|${k}|${r.join('/')}`);
    if (t && t.status !== 'missing' && t.status !== 'plays-israeli') return 'via-alias';
  }
  for (const tr of e.equivalentTo || []) {
    const t = index.get(`${e.voice}|${tr}|${e.kind}|${e.id}`);
    if (t && t.status !== 'missing' && t.status !== 'plays-israeli') return 'via-equivalent';
  }
  return 'missing';
}

export function buildIndex(manifest) { return new Map(manifest.map((e) => [`${e.voice}|${e.tradition}|${e.kind}|${e.id}`, e])); }

/** @returns {Array<{voice,tradition,group,required,recorded,tts,viaEquivalent,missing,optionalTotal,optionalMissing,aliasEntries}>} */
export function computeCoverage(manifest) {
  const index = buildIndex(manifest);
  const rows = new Map();
  const get = (e) => {
    const k = `${e.voice}|${e.tradition}|${e.group || 'other'}`;
    if (!rows.has(k)) rows.set(k, { voice: e.voice, tradition: e.tradition, group: e.group || 'other', required: 0, recorded: 0, tts: 0, viaEquivalent: 0, missing: 0, optionalTotal: 0, optionalMissing: 0, aliasEntries: 0 });
    return rows.get(k);
  };
  for (const e of manifest) {
    const r = get(e);
    if (e.aliasOf) { r.aliasEntries++; continue; }
    const st = entryState(e, index);
    if (e.optional) { r.optionalTotal++; if (st === 'missing') r.optionalMissing++; continue; }
    r.required++;
    if (st === 'recorded') r.recorded++; else if (st === 'tts') r.tts++; else if (st === 'via-equivalent') r.viaEquivalent++; else r.missing++;
  }
  const ord = (g) => { const i = GROUP_ORDER.indexOf(g); return i < 0 ? 99 : i; };
  return [...rows.values()].sort((a, b) => a.tradition.localeCompare(b.tradition) || a.voice.localeCompare(b.voice) || ord(a.group) - ord(b.group));
}

export function totals(rows) {
  const t = { required: 0, recorded: 0, tts: 0, viaEquivalent: 0, missing: 0 };
  for (const r of rows) for (const k of Object.keys(t)) t[k] += r[k];
  return t;
}

const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');

export function renderMarkdown(manifest) {
  const rows = computeCoverage(manifest);
  const L = [];
  L.push('# Audio coverage report', '',
    'Generated by `node tools/audio/coverage.mjs --write` from data/audio/manifest.json. Do not edit by hand.', '',
    'Reading this table: "required" counts the clips the app can ask for (optional whole-prayer reads and aliases excluded). "have" = recorded + tts + covered by a configured equivalence rule. A clip counts only if its file existed when the manifest was built.', '',
    `Status labels (the same table the app shows, src/shell/audio-labels.js): recorded = "${STATUS_LABELS.recorded}"; tts = "${STATUS_LABELS.tts}"; missing = "${STATUS_LABELS.missing}".`, '');
  const t = totals(rows);
  const have = t.recorded + t.tts + t.viaEquivalent;
  L.push(`**Overall: ${have} of ${t.required} required clips exist (${pct(have, t.required)}); ${STATUS_LABELS.recorded}: ${t.recorded}; ${STATUS_LABELS.tts}: ${t.tts}; ${STATUS_LABELS.missing}: ${t.missing}.**`, '');
  if (t.recorded === 0 && t.tts === 0) L.push('**No audio files exist in this repository. There are no real recordings and no TTS renders. Every clip is missing, and the app falls back to the browser Web Speech voice (Israeli only).**', '');
  L.push('## By talent and group', '');
  const byTalent = new Map();
  for (const r of rows) { const k = `${r.voice}|${r.tradition}`; if (!byTalent.has(k)) byTalent.set(k, []); byTalent.get(k).push(r); }
  for (const [k, list] of byTalent) {
    const tt = totals(list);
    L.push(`### ${TALENT[k] || k}  (voice=${k.split('|')[0]}, tradition=${k.split('|')[1]})`, '',
      `Required ${tt.required}; have ${tt.recorded + tt.tts + tt.viaEquivalent}; missing ${tt.missing}.`, '',
      '| group | required | recorded | tts | via equivalent | missing | optional (missing/total) | who can supply |', '|---|---:|---:|---:|---:|---:|---:|---|');
    for (const r of list) {
      const who = suppliers({ tradition: r.tradition, group: r.group });
      L.push(`| ${r.group} | ${r.required} | ${r.recorded} | ${r.tts} | ${r.viaEquivalent} | ${r.missing} | ${r.optionalMissing}/${r.optionalTotal} | ${who} |`);
    }
    L.push('');
  }
  L.push('## Notes', '',
    '- Phrasebook, mnemonic anchor words and the vocabulary of `israel`-track lessons are `scope: israeli-only` (Modern conversational Hebrew): they have no sephardi/ashkenazi entries, and the player plays the israeli clip whatever the congregation setting. This is a product decision recorded in the manifest, not a linguistic finding; change it in tools/audio/build_manifest.mjs if the owner disagrees.',
    '- Existing synthetic clips, missing clips and configured equivalences are counted above from the current manifests. An equivalence is a configured fallback, not a native-speaker approval.',
    '- "who can supply": isolated sounds, letter/vowel names and syllables are human-only. Israeli words/lines/phrases could come from TTS only after the listening test in docs/voices/tts-evaluation-protocol.md passes; Ashkenazi and Sephardi clips can only be made as synthetic voice from a Latin-letter respelling ("sound words", docs/tts/SOUNDWORDS.md); that method is an experiment, and how it sounds is unknown until a native listener hears it (docs/tts/PRODUCTION-ORDER.md steps 8 and 9). Existing synthetic clips are not proof of pronunciation or accent correctness. Human review remains necessary.', '');
  return L.join('\n');
}

/** "who is missing what": filter missing required entries. */
export function whoIsMissing(manifest, { voice, tradition, group, kind } = {}) {
  const index = buildIndex(manifest);
  return manifest.filter((e) => (!voice || e.voice === voice) && (!tradition || e.tradition === tradition) && (!group || e.group === group) && (!kind || e.kind === kind)
    && !e.optional && !e.aliasOf && entryState(e, index) === 'missing');
}

export function renderWho(manifest, opts = {}) {
  const miss = whoIsMissing(manifest, opts);
  const by = new Map();
  for (const e of miss) {
    const k = `${e.voice}|${e.tradition}`;
    if (!by.has(k)) by.set(k, new Map());
    by.get(k).set(e.group, (by.get(k).get(e.group) || 0) + 1);
  }
  const out = [];
  for (const k of Object.keys(TALENT)) {
    if (!by.has(k)) continue;
    const groups = by.get(k);
    const total = [...groups.values()].reduce((a, b) => a + b, 0);
    out.push(`${TALENT[k]} [${k.replace('|', '/')}]: missing ${total}`);
    for (const g of GROUP_ORDER) if (groups.has(g)) out.push(`    ${String(groups.get(g)).padStart(5)}  ${g}  (${suppliers({ tradition: k.split('|')[1], group: g })})`);
  }
  if (!out.length) out.push('Nothing missing for this filter.');
  if (opts.list) for (const e of miss.slice(0, opts.limit || miss.length)) out.push(`${e.path}\t${e.group}\t${e.text}`);
  return out.join('\n');
}

export function main(argv = process.argv.slice(2)) {
  const a = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (['--write', '--check', '--who', '--list'].includes(k)) a[k.slice(2)] = true;
    else if (k.startsWith('--')) a[k.slice(2)] = argv[++i];
  }
  const manifest = loadManifest();
  if (a.who) {
    for (const [k, list, label] of [['voice', VOICES, 'voice'], ['tradition', TRADS, 'tradition']]) if (a[k] && !list.includes(a[k])) { console.error(`--${label} must be one of ${list.join('|')}`); process.exit(2); }
    console.log(renderWho(manifest, { voice: a.voice, tradition: a.tradition, group: a.group, kind: a.kind, list: a.list, limit: a.limit ? +a.limit : undefined }));
    return;
  }
  const md = renderMarkdown(manifest);
  const target = path.join(ROOT, 'docs/voices/coverage.md');
  if (a.check) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (cur !== md) { console.error('docs/voices/coverage.md is stale; run: node tools/audio/coverage.mjs --write'); process.exit(1); }
    console.log('coverage.md is current'); return;
  }
  if (a.write) { fs.writeFileSync(target, md); console.log('wrote docs/voices/coverage.md'); }
  const rows = computeCoverage(manifest);
  const t = totals(rows);
  console.log(`required ${t.required}  recorded ${t.recorded}  tts ${t.tts}  via-equivalent ${t.viaEquivalent}  missing ${t.missing}`);
  console.log(renderWho(manifest, {}));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
