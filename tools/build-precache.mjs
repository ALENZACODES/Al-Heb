// Generates precache-manifest.js (list of app-shell + data files and a content-hash version) for sw.js.
// Run: node tools/build-precache.mjs   (re-run whenever files under src/, data/, assets/ change)
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const INCLUDE_DIRS = ['src', 'assets', 'data'];
const SKIP = (rel) => rel.startsWith('assets/img/') /* big, runtime-cached */ || rel.split('/').some((p) => p.startsWith('_') || p === 'node_modules')
  || rel.endsWith('.py') || rel.endsWith('.md') || /\.(mp3|wav|ogg|m4a|svg\.src|ttf|otf|txt)$/i.test(rel)  // original TTFs and licence texts are not precached; woff2 in assets/fonts/web/ is
  || rel.split('/').includes('tools')
  || rel.startsWith('data/images/') || rel === 'data/corpus/source-snapshot.json'; // build-time inputs, not fetched by the app
const DATA_ONLY_JSON = (rel) => !rel.startsWith('data/') || rel.endsWith('.json');

function walk(dir, out = [], root = repoRoot) {
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out, root); else out.push(relative(root, p).split(sep).join('/'));
  }
  return out;
}

/** @param {string} [root] site root to scan (repo root by default; tools/build-static.mjs passes dist/) */
export function computeManifest(root = repoRoot) {
  const files = ['index.html', 'offline.html', 'manifest.webmanifest'];
  for (const d of INCLUDE_DIRS) { try { files.push(...walk(join(root, d), [], root).filter((r) => !SKIP(r) && DATA_ONLY_JSON(r))); } catch { /* dir missing */ } }
  const hash = createHash('sha256');
  for (const f of files) { hash.update(f); hash.update(readFileSync(join(root, f))); }
  return { files, version: hash.digest('hex').slice(0, 12) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const m = computeManifest();
  const root = repoRoot;
  const body = `// GENERATED by tools/build-precache.mjs - do not edit.\nself.ALEF_VERSION = ${JSON.stringify(m.version)};\nself.ALEF_PRECACHE = ${JSON.stringify(m.files, null, 1)};\n`;
  writeFileSync(join(root, 'precache-manifest.js'), body);
  console.log(`precache-manifest.js: ${m.files.length} files, version ${m.version}`);
}
