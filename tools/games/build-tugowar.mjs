#!/usr/bin/env node
// Builds Antonym Tug-of-War's 600-round bank from tools/games/tugowar-bank.psv.
//   node tools/games/build-tugowar.mjs           write src/games/tugowar.bank.js and docs/games/tugowar-images.csv
//   node tools/games/build-tugowar.mjs --check   exit 1 if either file is out of date (used by the test)
// Each pair is matched to the vocabulary index (data/vocab/index.json) so the game can play a word clip
// (audio/<m|f>/israeli/word/<id>.mp3) when one exists. A pointed spelling that differs from the vocabulary's is reported.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const r = (p) => join(ROOT, p);
const check = process.argv.includes('--check');

const strip = (s) => String(s).replace(/[֑-ׇ]/g, '').replace(/[־־]/g, '').trim();
const lines = readFileSync(r('tools/games/tugowar-bank.psv'), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#'));
const rows = lines.map((l, i) => {
  const c = l.split('|');
  if (c.length !== 10) throw new Error(`line ${i + 1}: expected 10 columns, got ${c.length}`);
  return { key: c[0], he1: c[1], tr1: c[2], en1: c[3], he2: c[4], tr2: c[5], en2: c[6], pos: c[7], pic: c[8], scene: c[9] };
});
if (rows.length !== 300) throw new Error(`the bank needs exactly 300 pairs (600 rounds); it has ${rows.length}`);
const keys = new Set();
for (const p of rows) { if (keys.has(p.key)) throw new Error(`duplicate key ${p.key}`); keys.add(p.key); }

const vocab = JSON.parse(readFileSync(r('data/vocab/index.json'), 'utf8'));
const F = Object.fromEntries(vocab.fields.map((f, i) => [f, i]));
const byPointed = new Map(), byPlain = new Map();
for (const row of vocab.rows) {
  const he = row[F.he];
  if (!byPointed.has(he)) byPointed.set(he, row);
  const plain = row[F.heUnpointed] || strip(he);
  if (!byPlain.has(plain)) byPlain.set(plain, []);
  byPlain.get(plain).push(row);
}
const hasClip = (id) => existsSync(r(`audio/m/israeli/word/${id}.mp3`)) || existsSync(r(`audio/f/israeli/word/${id}.mp3`));
const notes = [];
function audioFor(he) {
  const exact = byPointed.get(he);
  if (exact) return hasClip(exact[F.id]) ? exact[F.id] : '';
  const near = byPlain.get(strip(he)) || [];
  if (near.length) notes.push(`${he}: vocabulary spells it ${near.map((n) => n[F.he]).join(' / ')} (no clip used)`);
  return '';
}

function picOf(p) {
  if (p.pic.startsWith('id:')) return p.pic;
  if (p.pic.startsWith('=')) {
    const base = rows.find((x) => x.key === p.pic.slice(1));
    if (!base) throw new Error(`${p.key}: picture refers to unknown pair ${p.pic}`);
    return picOf(base);
  }
  if (!p.scene) throw new Error(`${p.key}: own picture needs a scene`);
  return `TUG_${p.key}`;
}

const bank = rows.map((p) => [p.key, p.he1, p.tr1, p.en1, p.he2, p.tr2, p.en2, p.pos, picOf(p), audioFor(p.he1), audioFor(p.he2)]);
const js = `// Generated by tools/games/build-tugowar.mjs from tools/games/tugowar-bank.psv. Do not edit by hand.
// [key, hebrew, translit, english, oppositeHebrew, oppositeTranslit, oppositeEnglish, pos, picture, audioId, oppositeAudioId]
// picture: 'id:<resolver id>' or a stem under assets/games/tugowar/pairs/<stem>.png. audio ids are vocabulary ids with a word clip.
export const BANK = Object.freeze(${JSON.stringify(bank, null, 0).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]')});
`;

const q = (s) => `"${String(s).replace(/"/g, '""')}"`;
const own = rows.filter((p) => !p.pic);
const csv = ['path,key,pair,scene', ...own.map((p) => [q(`assets/games/tugowar/pairs/TUG_${p.key}.png`), q(p.key), q(`${p.en1} / ${p.en2}`), q(p.scene)].join(','))].join('\n') + '\n';

// Ready-to-paste batches of ten for the picture run (master command in docs/games/TUGOWAR-COMMANDS.md).
const batches = [];
for (let i = 0; i < own.length; i += 10) {
  const part = own.slice(i, i + 10);
  batches.push(`## Batch ${batches.length + 1} of ${Math.ceil(own.length / 10)}\n\n\`\`\`\nDraw these ${part.length} pictures, one image each, square 1024 x 1024, house style and rules as before. Left half = the first word, right half = its opposite. Save each with exactly the file name given.\n${part.map((p, j) => `${j + 1}. TUG_${p.key}.png: ${p.scene}.`).join('\n')}\n\`\`\``);
}
const md = `# Tug-of-War picture batches\n\nGenerated by \`node tools/games/build-tugowar.mjs\`. Paste the master command from \`docs/games/TUGOWAR-COMMANDS.md\` once, then one batch at a time. Every file goes to \`assets/games/tugowar/pairs/\`.\n\n${batches.join('\n\n')}\n`;

const outs = [['src/games/tugowar.bank.js', js], ['docs/games/tugowar-images.csv', csv], ['docs/games/tugowar-image-batches.md', md]];
let stale = 0;
for (const [path, body] of outs) {
  const cur = existsSync(r(path)) ? readFileSync(r(path), 'utf8') : '';
  if (cur === body) continue;
  stale++;
  if (!check) writeFileSync(r(path), body);
}
if (check) { if (stale) { console.error(`${stale} generated file(s) out of date: run node tools/games/build-tugowar.mjs`); process.exit(1); } process.exit(0); }
const withAudio = bank.reduce((n, b) => n + (b[9] ? 1 : 0) + (b[10] ? 1 : 0), 0);
console.log(`${rows.length} pairs -> 600 rounds; ${own.length} pairs need their own picture; ${withAudio}/600 words have a clip.`);
for (const n of notes) console.log('  spelling note:', n);
