#!/usr/bin/env node
// Usage: node tools/hebrew-lint/cli.mjs [--data DIR] [--report] [--update-baseline]
// Report-only. Never modifies data files. --report writes docs/hebrew-lint/REPORT.md and report.json.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { RULES, scanDir } from './lint.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
export const fingerprint = (f) => `${f.file}|${f.rule}|${f.path}|${crypto.createHash('sha1').update(f.sample).digest('hex').slice(0, 8)}`;

export function summarize(res) {
  const perRule = {}; for (const r of Object.keys(RULES)) perRule[r] = { class: RULES[r].cls, reason: RULES[r].reason, count: 0, files: 0, examples: [] };
  const fileSets = {}; const exFiles = {};
  for (const f of res.findings) {
    const pr = perRule[f.rule]; pr.count++;
    (fileSets[f.rule] ||= new Set()).add(f.file);
    exFiles[f.rule] ||= new Set();
    if (pr.examples.length < 5 && !exFiles[f.rule].has(f.file)) { exFiles[f.rule].add(f.file); pr.examples.push({ file: f.file, path: f.path, detail: f.detail, text: f.snippet }); }
  }
  for (const f of res.findings) { const pr = perRule[f.rule]; if (pr.examples.length < 5 && !pr.examples.some((e) => e.file === f.file && e.path === f.path)) pr.examples.push({ file: f.file, path: f.path, detail: f.detail, text: f.snippet }); }
  for (const r of Object.keys(perRule)) perRule[r].files = fileSets[r]?.size || 0;
  const perFile = res.files.filter((f) => Object.keys(f.counts).length).map((f) => ({ file: f.file, hebrewStrings: f.hebrewStrings, counts: f.counts, total: Object.values(f.counts).reduce((a, b) => a + b, 0) })).sort((a, b) => b.total - a.total || a.file.localeCompare(b.file));
  return { scannedFiles: res.scannedFiles, hebrewStrings: res.hebrewStrings, parseErrors: res.parseErrors, perRule, perFile };
}

export function buildBaseline(res) {
  const sum = summarize(res);
  const counts = {}; for (const r of Object.keys(RULES)) counts[r] = sum.perRule[r].count;
  const definite = res.findings.filter((f) => RULES[f.rule].cls === 'definite').map(fingerprint).sort();
  return { note: 'Counts of current findings. The test fails only on definite-error fingerprints (file|rule|path|hash of string) absent here. Regenerate deliberately with: node tools/hebrew-lint/cli.mjs --update-baseline', counts, definiteFingerprints: definite };
}

const md = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const cps = (t) => [...t].filter((c) => /[\u0590-\u05cf\u200b-\u200f\u202a-\u202e\u2060-\u2069\ufeff\u00ad\ufb1d-\ufb4f]/.test(c) && !/[\u05d0-\u05ea]/.test(c)).map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'));

export function renderReport(sum) {
  const L = [];
  L.push('# Hebrew lint report', '');
  L.push('Generated by `node tools/hebrew-lint/cli.mjs --report`. The linter only reports; it changes no data.', '');
  L.push('**Passing this linter is NOT proof of correct Hebrew.** It checks code points and spacing only. It cannot detect wrong words, misspellings, wrong vowels that are validly placed, wrong grammar, wrong translation, or bad transliteration. Native review is still required.', '');
  L.push(`Scanned ${sum.scannedFiles} JSON files under data/ (${sum.hebrewStrings} strings containing Hebrew, including object keys). Unparseable files: ${sum.parseErrors.length}.`, '');
  L.push('## Canonical mark order', '', 'Marks on one letter must follow Unicode canonical order (the order NFC produces): letter, vowels (sheva through qubuts), dagesh/mapiq, meteg, rafe, shin/sin dot, then cantillation by combining class. This matches the repo normalisation test. It is the opposite of "dot first" orderings some fonts tutorials show, so a string typed dot-first is reported by mark-order.', '');
  L.push('## Reading the numbers', '', '- `data/photo/_benchmark/*` holds raw OCR engine output, which is malformed on purpose; its findings are expected and not data bugs.', '- `data/corpus/source-snapshot.json` keeps source text as received (shin/sin dot before vowel, HTML-like tags, cantillation); the runtime pipeline normalises it, so its mark-order count is a property of the snapshot, not of displayed text.', '- Isolated marks shown as specimens (alone, in parentheses, or after a dotted circle) are not flagged as stray.', '- Fragment fields (syllables, marked segments, folded dropTokens) are exempt from nonfinal-letter-at-end by path.', '- Counts are per finding, not per string; one string can raise several.', '');
  L.push('## Rules and counts', '', '| Rule | Class | Count | Files | Why |', '|---|---|---:|---:|---|');
  for (const cls of ['definite', 'style']) for (const [r, v] of Object.entries(sum.perRule)) if (v.class === cls) L.push(`| ${r} | ${cls === 'definite' ? 'definite error' : 'style/convention'} | ${v.count} | ${v.files} | ${md(v.reason)} |`);
  L.push('', '"definite error" means the text is invalid or inconsistent at code-point level. "style/convention" means it renders and reads but departs from convention, or may be deliberate.', '');
  L.push('## Examples (up to 5 per rule, different files first)', '');
  for (const [r, v] of Object.entries(sum.perRule)) {
    if (!v.count) continue;
    L.push(`### ${r} (${v.class === 'definite' ? 'definite error' : 'style/convention'}, ${v.count})`, '');
    for (const e of v.examples) L.push(`- \`${e.file}\` \`${md(e.path)}\`: ${md(e.text)}${e.detail ? ' [' + md(e.detail) + ']' : ''}`);
    L.push('');
  }
  L.push('## Per file', '', '| File | Hebrew strings | Total findings | Per rule |', '|---|---:|---:|---|');
  for (const f of sum.perFile) L.push(`| ${f.file} | ${f.hebrewStrings} | ${f.total} | ${Object.entries(f.counts).map(([k, n]) => `${k}=${n}`).join(', ')} |`);
  L.push('', 'Files with no findings are omitted.', '');
  if (sum.parseErrors.length) { L.push('## Unparseable JSON', ''); for (const e of sum.parseErrors) L.push(`- ${e.file}: ${md(e.error)}`); L.push(''); }
  return L.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const a = process.argv.slice(2);
  const di = a.indexOf('--data');
  const dataDir = di >= 0 ? path.resolve(a[di + 1]) : path.join(root, 'data');
  const res = scanDir(dataDir, path.dirname(dataDir));
  const sum = summarize(res);
  if (a.includes('--report')) {
    fs.mkdirSync(path.join(root, 'docs/hebrew-lint'), { recursive: true });
    fs.writeFileSync(path.join(root, 'docs/hebrew-lint/REPORT.md'), renderReport(sum));
    fs.writeFileSync(path.join(root, 'docs/hebrew-lint/report.json'), JSON.stringify(sum, null, 1) + '\n');
  }
  if (a.includes('--update-baseline')) fs.writeFileSync(path.join(here, 'baseline.json'), JSON.stringify(buildBaseline(res), null, 1) + '\n');
  for (const [r, v] of Object.entries(sum.perRule)) console.log(`${v.class.padEnd(8)} ${r.padEnd(30)} ${v.count}`);
}
