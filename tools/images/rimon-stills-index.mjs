// Regenerates src/shell/rimon-stills-index.js from data/images/rimon/rimon-*.webp so the
// mascot only ever asks for stills that exist. Run: node tools/images/rimon-stills-index.mjs
import fs from 'node:fs';
const dir = new URL('../../data/images/rimon/', import.meta.url);
const ids = fs.readdirSync(dir).map((f) => /^rimon-(\d{3}[a-z]?)\.webp$/.exec(f)?.[1]).filter(Boolean).sort();
const out = `// Generated by tools/images/rimon-stills-index.mjs; do not edit by hand.\nexport const RIMON_STILLS_AVAILABLE = Object.freeze(new Set(${JSON.stringify(ids)}));\n`;
fs.writeFileSync(new URL('../../src/shell/rimon-stills-index.js', import.meta.url), out);
console.log(ids.length, 'stills indexed');
