// Regenerates src/shell/rimon-stills-index.js from data/images/rimon so the
// mascot only ever asks for stills that exist. The original numbered set uses
// plain ids (023). The v2 (Claude-order, slugged) catalogue uses v2:023 ids and
// is never treated as a replacement for the same-numbered drawn still.
// Legacy/ files are archived and are not indexed. Run: node tools/images/rimon-stills-index.mjs
import fs from 'node:fs';
const dir = new URL('../../data/images/rimon/', import.meta.url);
const v2dir = new URL('../../data/images/rimon/v2/', import.meta.url);

const v1 = fs.readdirSync(dir)
  .map((f) => /^rimon-(\d{3}[a-z]?)\.webp$/.exec(f)?.[1])
  .filter(Boolean)
  .sort();

const v2 = {};
if (fs.existsSync(v2dir)) {
  for (const f of fs.readdirSync(v2dir)) {
    const m = /^rimon-(\d{3}[a-z]?)-([a-z0-9-]+)\.webp$/.exec(f);
    if (!m) continue;
    // First match wins; ignore -alt siblings.
    if (!v2[m[1]]) v2[m[1]] = m[2];
  }
}

const ids = [...v1, ...Object.keys(v2).map((k) => `v2:${k}`)].sort();
const v2Lit = JSON.stringify(v2, null, 2).replace(/\n/g, '\n  ');
const out = `// Generated by tools/images/rimon-stills-index.mjs; do not edit by hand.
export const RIMON_STILLS_V2 = Object.freeze(${v2Lit});
export const RIMON_STILLS_AVAILABLE = Object.freeze(new Set(${JSON.stringify(ids)}));
`;
fs.writeFileSync(new URL('../../src/shell/rimon-stills-index.js', import.meta.url), out);
console.log(ids.length, 'stills indexed,', Object.keys(v2).length, 'from v2');
