assert.deepEqual(errors,[]);assert.deepEqual(badAssets,[]);
fs.writeFileSync(root+'docs/qa/rimon-results.json',JSON.stringify({poses:16,seen,routes,phoneWidth:375,dismissRestores:true,reducedMotionInitialAndDynamic:true,idleYawnVirtualClock:true,errors,badAssets},null,2)+'\n');
console.log(JSON.stringify({seen,routes,errors,badAssets}));await browser.close();
