import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root=fileURLToPath(new URL('../../',import.meta.url));
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || undefined});
const ctx=await browser.newContext({viewport:{width:960,height:800},recordVideo:{dir:root+'../rimon-video',size:{width:960,height:800}}});
const page=await ctx.newPage(), errors=[],badAssets=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400 && /rimon/.test(r.url()))badAssets.push(r.url());});
await page.addInitScript(()=>{
  window.rimonSeen=[];
  new MutationObserver(()=>{const s=document.querySelector('.rimon-dock .rimon-sprite');if(s)window.rimonSeen.push(s.dataset.action+':'+s.dataset.frame);}).observe(document,{subtree:true,attributes:true,attributeFilter:['data-frame']});
});
const start=Date.now();
await page.goto(process.env.RIMON_URL || 'http://127.0.0.1:8080/',{waitUntil:'networkidle'});
if(await page.locator('#alef-prayer-noshow').isVisible())await page.locator('#alef-prayer-noshow').click();
await page.locator('.home-builder').scrollIntoViewIfNeeded();
const at=async ms=>page.waitForTimeout(Math.max(0,ms-(Date.now()-start)));
await at(7000);
await page.locator('.home-builder > .builder-tray [data-glyph="ב"]').click();
await at(9500);
for(const glyph of ['א','ב','א'])await page.locator(`.home-builder > .builder-tray [data-glyph="${glyph}"]`).click();
await at(12500);
await page.evaluate(async()=>{
 const {store}=await import('/src/store.js');const {lessons}=await import('/src/curriculum/lessons.js');
 await (await import('/src/curriculum/actions.js')).completeLesson({store},lessons[0]);
});
await page.locator('.rimon-next').waitFor({state:'visible'});
assert.match(await page.locator('.rimon-next').getAttribute('href'),/^#\/learn\?lesson=/);
await at(16000);
await page.evaluate(async()=>{
 const {store}=await import('/src/store.js');const {lessons,belts}=await import('/src/curriculum/lessons.js');
 const {deriveBeginnerRubric}=await import('/src/awards/rubric.js');
 store.set('streak',{v:2,count:3,best:3,last:'2026-11-07',todayDate:'2026-11-07',todaySeconds:300,doneDates:['2026-11-05','2026-11-06','2026-11-07']});
 const result=(await import('/src/awards/eligibility.js')).settleAwards(store,deriveBeginnerRubric(lessons,belts),Date.now());
 if(!result.record.awards['streak-3'])throw Error('streak badge was not earned');
});
await at(20500);
const seen=[...new Set(await page.evaluate(()=>window.rimonSeen))];
for(const action of ['wave','blink','sad','laugh','bounce','point','stretch'])assert.ok(seen.some(s=>s.startsWith(action+':')),action+' observed');
await page.screenshot({path:root+'docs/qa/rimon-desktop.png'});
const video=page.video();await ctx.close();fs.writeFileSync(root+'../rimon-video/latest.txt',await video.path());
const check=await browser.newPage({viewport:{width:375,height:812},isMobile:true,hasTouch:true});check.on('pageerror',e=>errors.push(e.message));
await check.goto(process.env.RIMON_URL || 'http://127.0.0.1:8080/',{waitUntil:'networkidle'});
if(await check.locator('#alef-prayer-noshow').isVisible())await check.locator('#alef-prayer-noshow').click();
const routes=['/','/awards','/progress','/daily'];
for(const route of routes){await check.evaluate(r=>location.hash='#'+r,route);await check.waitForTimeout(700);assert.ok(await check.locator('.rimon-dock').isVisible(),route);assert.equal(await check.locator('.alef-unavailable').count(),0,route);}
await check.screenshot({path:root+'docs/qa/rimon-phone.png'});
await check.getByRole('button',{name:'Hide Rimon',exact:true}).tap();assert.equal(await check.locator('.rimon-dock').isVisible(),false);
await check.reload({waitUntil:'networkidle'});assert.equal(await check.locator('.rimon-dock').isVisible(),false);
await check.getByRole('button',{name:'Show Rimon',exact:true}).tap();assert.ok(await check.locator('.rimon-dock').isVisible());
await check.emulateMedia({reducedMotion:'reduce'});await check.waitForTimeout(200);
const still=await check.locator('.rimon-dock .rimon-sprite').evaluate(e=>({action:e.dataset.action,frame:e.dataset.frame,animation:getComputedStyle(e).animationName,transform:getComputedStyle(e).transform}));
assert.deepEqual(still,{action:'still',frame:'0',animation:'none',transform:'none'});
await check.evaluate(async()=>{(await import('/src/shell/rimon-events.js')).signalRimon('correct');});await check.waitForTimeout(1300);
assert.equal(await check.locator('.rimon-dock .rimon-sprite').getAttribute('data-frame'),'0');
await check.emulateMedia({reducedMotion:'no-preference'});await check.waitForTimeout(100);assert.equal(await check.locator('.rimon-dock .rimon-sprite').getAttribute('data-action'),'idle');
const reduced=await browser.newPage({reducedMotion:'reduce'});await reduced.goto(process.env.RIMON_URL || 'http://127.0.0.1:8080/',{waitUntil:'networkidle'});assert.equal(await reduced.locator('.rimon-dock .rimon-sprite').getAttribute('data-action'),'still');
