// Verdict store helpers shared by the builder (status counts) and ingest.
import fs from 'node:fs';
import { REVIEWER_TYPES } from './instructions.mjs';

export const SCHEMA = 'alef-review-verdicts/1';
export const NOTE = 'Reviewer answers recorded by tools/review/ingest.mjs from returned CSVs. Content files are never changed by ingest; a Fix is a suggestion that a person applies by hand.';

export function emptyStore() { return { schema: SCHEMA, note: NOTE, verdicts: {} }; }

export function loadVerdicts(file) {
  if (!fs.existsSync(file)) return emptyStore();
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (j.schema !== SCHEMA || typeof j.verdicts !== 'object') throw new Error(`${file}: not an ${SCHEMA} file`);
  return j;
}

// Stable serialisation: ids sorted, entries sorted by reviewerType then reviewer.
export function serialise(store) {
  const out = { schema: SCHEMA, note: NOTE, verdicts: {} };
  for (const id of Object.keys(store.verdicts).sort()) {
    out.verdicts[id] = [...store.verdicts[id]].sort((a, b) => (a.reviewerType + '\0' + a.reviewer).localeCompare(b.reviewerType + '\0' + b.reviewer)).map((e) => ({ reviewerType: e.reviewerType, reviewer: e.reviewer, date: e.date, verdict: e.verdict, correction: e.correction, notes: e.notes, hebrewSeen: e.hebrewSeen }));
  }
  return JSON.stringify(out, null, 1) + '\n';
}

// Per-id overall: Fix beats Unsure beats OK.
export function overall(entries) {
  if (entries.some((e) => e.verdict === 'Fix')) return 'Fix';
  if (entries.some((e) => e.verdict === 'Unsure')) return 'Unsure';
  return 'OK';
}

export function summarise(all, store) {
  const packs = all.map((p) => {
    const c = { OK: 0, Fix: 0, Unsure: 0 };
    for (const r of p.rows) { const e = store.verdicts[r.id]; if (e && e.length) c[overall(e)]++; }
    return { key: p.key, num: p.num, title: p.title, file: p.file, rows: p.rows.length, ...c, reviewed: c.OK + c.Fix + c.Unsure };
  });
  const known = new Set(all.flatMap((p) => p.rows.map((r) => r.id)));
  const orphan = Object.keys(store.verdicts).filter((id) => !known.has(id)).length;
  return { packs, total: packs.reduce((n, p) => n + p.rows, 0), reviewed: packs.reduce((n, p) => n + p.reviewed, 0), OK: packs.reduce((n, p) => n + p.OK, 0), Fix: packs.reduce((n, p) => n + p.Fix, 0), Unsure: packs.reduce((n, p) => n + p.Unsure, 0), orphan };
}

export function statusMd(all, sum, packet = null) {
  const L = ['# Review status', '', 'Generated by `node tools/review/build-packs.mjs` from the data files and `data/review/verdicts.json` (absent means no verdicts yet). Re-run it after every ingest.', ''];
  L.push(sum.reviewed === 0
    ? '**Reviewed: 0 of ' + sum.total + ' rows.** No native speaker, Hebrew teacher or clergy member has returned a verdict. Every Hebrew string in the app, including the rows below, is an unreviewed draft.'
    : `**Reviewed: ${sum.reviewed} of ${sum.total} rows** (OK ${sum.OK}, Fix ${sum.Fix}, Unsure ${sum.Unsure}). A row counts as reviewed once at least one reviewer returned a verdict for it; this is not a statement that the rest is wrong, nor that OK rows are certified. Fix rows are suggestions that a person has not applied yet.`);
  L.push('', '| Pack | Rows | Reviewed | OK | Fix | Unsure | Not reviewed |', '|---|---|---|---|---|---|---|');
  for (const p of sum.packs) L.push(`| ${p.num} ${p.title} | ${p.rows} | ${p.reviewed} | ${p.OK} | ${p.Fix} | ${p.Unsure} | ${p.rows - p.reviewed} |`);
  L.push(`| **Total** | **${sum.total}** | **${sum.reviewed}** | **${sum.OK}** | **${sum.Fix}** | **${sum.Unsure}** | **${sum.total - sum.reviewed}** |`);
  if (sum.orphan) L.push('', `Verdicts whose id no longer exists in the data: ${sum.orphan} (data changed since they were recorded).`);
  if (packet) L.push('', '## Area packets (build_packet.mjs, `docs/review/out/manifest.json`)', '',
    `${packet.totalItems} items in ${packet.areas} areas, about ${packet.totalHours.toFixed(1)} reviewer hours by the time model (phase one, priority 1 to 6: ${packet.phaseOneItems} items, ${packet.phaseOneHours.toFixed(1)} h). The hours are an estimate from a per-item model, not a measurement. Safety-net area \`other-flagged\` (flagged data no area claims): ${packet.otherFlagged} items; flagged files with no area: ${packet.uncovered}.`);
  L.push('', '## What this does and does not cover', '',
    '- Covered: word lists of the core and intermediate lessons, the 1000 most frequent vocabulary words, prayer and Torah registry lines, the trope table and two cantillated texts, the pronunciation rule list and a stratified sample of respellings per tradition, dialogues and speaking sets, festival vocabulary.',
    '- Not covered by these seven packs: lesson titles and goals, exercise prompts, example sentences, other vocabulary beyond rank 1000, letter-stroke cards, the calendar, the book, audio (none exists). The area-based packets (`tools/review/build_packet.mjs`, see `docs/review/README.md`) cover many of these.',
    '- The pronunciation pack holds the rule list and a sample of about 200 rule-generated respellings per tradition (every rule on at least two rows where the data has two); the other ~6,000 respellings (6,630 derived records in all) come from the same rules and are not sent row by row. Those rules and the three traditions were set by the project, not by a reviewer.',
    '- Reviewer types: ' + Object.values(REVIEWER_TYPES).join('; ') + '.',
    '', 'Workflow: build packs, send CSV (and the print HTML) with INSTRUCTIONS.md, then `node tools/review/ingest.mjs returned.csv --reviewer NAME --type teacher|cantor|native --date YYYY-MM-DD` (dry run), add `--write` to record. Ingest never edits content.', '');
  return L.join('\n');
}
