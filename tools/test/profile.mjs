// Profile test files: node tools/test/profile.mjs [--jobs N] [glob-ish prefix filter]
// Runs each tests/*.test.js as its own `node --test` process, N at a time, and writes docs/test/TIMINGS.md.
import { spawn } from 'node:child_process';
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { cpus } from 'node:os';
const args = process.argv.slice(2);
const ji = args.indexOf('--jobs');
const jobs = ji >= 0 ? +args[ji + 1] : Math.max(1, cpus().length);
const filter = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--jobs')[0] || '';
const files = readdirSync('tests').filter(f => f.endsWith('.test.js') && f.includes(filter)).map(f => 'tests/' + f);
const rows = [];
let next = 0;
function run(f) {
  return new Promise(res => {
    const t0 = Date.now();
    const p = spawn(process.execPath, ['--test', f], { stdio: ['ignore', 'pipe', 'pipe'] });
    let out = '';
    p.stdout.on('data', d => out += d); p.stderr.on('data', d => out += d);
    p.on('close', code => {
      const m = k => +(out.match(new RegExp('^# ' + k + ' (\\d+)', 'm')) || [0, 0])[1];
      rows.push({ f, s: (Date.now() - t0) / 1000, code, tests: m('tests'), fail: m('fail') });
      res();
    });
  });
}
await Promise.all(Array.from({ length: jobs }, async () => { while (next < files.length) await run(files[next++]); }));
rows.sort((a, b) => b.s - a.s);
const total = rows.reduce((a, r) => a + r.s, 0);
const md = ['# Test timings', '', `Generated by tools/test/profile.mjs (jobs=${jobs}). Per-file wall seconds under that load (sum ${(total / 60).toFixed(1)} min).`, '',
  '| s | file | tests | fail |', '|---:|---|---:|---:|', ...rows.map(r => `| ${r.s.toFixed(1)} | ${r.f} | ${r.tests} | ${r.fail} |`), ''].join('\n');
mkdirSync('docs/test', { recursive: true });
writeFileSync('docs/test/TIMINGS.md', md);
console.log(md.split('\n').slice(0, 24).join('\n'));
