#!/usr/bin/env python3
"""Topic-coverage check of data/vocab/vocab5000.json against a user-supplied reference sheet (licence UNSTATED).

The sheet is used ONLY to count, per topic section, how many of its items are matched by our vocabulary.
Nothing from the sheet is written to the repo: the output holds section names and counts only.
Usage: python3 -I tools/vocab/coverage.py /path/to/top625-user-supplied.csv [--write]
Matching: unpointed Hebrew equals a vocabulary lemma, or an inflected form of one (forms from words.json);
slash-separated alternatives count as matched if any alternative matches. Multi-word items need an exact lemma.
"""
import csv, json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
NIQ = re.compile('[֑-ׇ]')
strip = lambda s: NIQ.sub('', s).replace('־', ' ').replace('׳', "'").strip()

vocab = json.load(open(os.path.join(ROOT, 'data/vocab/vocab5000.json'), encoding='utf8'))['entries']
lemmas = {e['lemma'] for e in vocab}
words = json.load(open(os.path.join(ROOT, 'data/vocab/words.json'), encoding='utf8'))['words']
forms = set(lemmas)
for w in words:
    if w['heUnpointed'] in lemmas:
        for v in (w.get('forms') or {}).values():
            if isinstance(v, str):
                forms.add(strip(v))
            elif isinstance(v, list):
                forms.update(strip(x) for x in v if isinstance(x, str))
# the topic of a lemma in OUR vocabulary, to report topics where the item exists but is filed elsewhere
rows = list(csv.reader(open(sys.argv[1], encoding='utf8')))
sec, stats = None, {}
for r in rows[1:]:
    if len(r) < 2 or not (r[0] or r[1]).strip():
        continue
    if r[0].strip().endswith(':') and not r[3 if len(r) > 3 else 1].strip().count(' ') > 3:
        sec = r[0].strip().rstrip(':')
        stats[sec] = [0, 0]
        continue
    if sec is None:
        continue
    alts = [strip(a) for a in re.split(r'[/,]', r[1]) if a.strip()]
    stats[sec][0] += 1
    if any(a in forms for a in alts):
        stats[sec][1] += 1
tot = sum(v[0] for v in stats.values()); hit = sum(v[1] for v in stats.values())
print('sections', len(stats), 'items', tot, 'matched', hit, 'gaps', tot - hit)
for k, (n, m) in stats.items():
    print('%-22s items %3d matched %3d gap %3d' % (k, n, m, n - m))
if '--write' in sys.argv:
    out = ['# Vocabulary vs reference-sheet topic coverage (counts only)', '',
           'Generated by `tools/vocab/coverage.py`. The reference sheet has an UNSTATED licence; it was used only to count',
           'matches and nothing from it is stored in this repository. A "gap" means no vocabulary lemma or inflected form',
           'equals the sheet item after stripping niqqud (slash alternatives: any one matching counts). Multi-word items need',
           'an exact lemma, so many gaps are phrases or alternative wordings rather than missing words.', '',
           '| Sheet section | Items | Matched | Gaps |', '|---|---:|---:|---:|']
    for k, (n, m) in stats.items():
        out.append('| %s | %d | %d | %d |' % (k, n, m, n - m))
    out.append('| **Total** | %d | %d | %d |' % (tot, hit, tot - hit))
    open(os.path.join(ROOT, 'docs/vocab/COVERAGE.md'), 'w', encoding='utf8').write('\n'.join(out) + '\n')
